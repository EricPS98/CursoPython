"""
Operador
== Igual
!= Diferente De
> Maior que
< Menor que
>= Maior ou igual que
<= Menor ou igual que
"""

letra = "b"

# Operador == Igual
# if = Se
if letra == "a":
    print("A letra é igual a Letra A")

# Operador != Diferente De
if letra != "a":
    print("A letra é diferente de A")

# Operador > Maior que
numero1 = 20
numero2 = 15

if numero1 > numero2:
    print("O numero1 é maior que o numero2")

# Operador < Menor que
n1 = 15
n2 = 30

if n1 < n2:
    print("O numero2 é maior que o numero1")

# Operador >= Maior ou igual que
num1 = 20

if num1 >= 20:
    print("O num1 é maior ou igual a 20")

# Operador <= Menor ou igual que
num2 = 10

if num2 <= 15:
    print("O num2 é menor ou igual a 15")