"""
== Igual : Verifica se um valor é igual ao outro
!= Diferente de : Verifica se um valor é diferente do outro
> Maior que : Verifica se um valor é maior que o outro
>= Maior ou igual : Verifica se um valor é maior ou igual ao outro
< Menor que : Verifica se um valor é menor que o outro
<= Menor ou igual : Verifica se um valor é menor ou igual ao outro
"""

numero1 = 10
numero2 = 10

if numero1 == numero2:
    print("Ambos os números são iguais")

if numero1 != numero2:
    print("Os números são diferentes")

if numero1 > numero2:
    print("Número 1 é maior que o Número 2")

if numero1 >= numero2:
    print("Número 1 é maior ou igual ao Número 2")

if numero1 < numero2:
    print("Número 1 é menor que o Número 2")

if numero1 <= numero2:
    print("Número 1 é menor ou igual ao Número 2")

